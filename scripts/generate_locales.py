#!/usr/bin/env python3
"""Validate the shared UI catalog and generate the Kotlin copy (no build dependency)."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "locales/en.json"
KOTLIN = ROOT / "app/src/commonMain/kotlin/kim/jujin/rovessh/core/EnglishCatalog.kt"

def generated():
    pairs = json.loads(CATALOG.read_text(encoding="utf-8"), object_pairs_hook=list)
    if len({key for key, _ in pairs}) != len(pairs):
        raise ValueError("Duplicate message key")
    keys = {key for key, _ in pairs}
    roots = ["desktop/src", "crates/dgl-core/src", "app/src/commonMain", "app/src/jvmSharedMain",
             "app/src/androidMain", "mobileUi/src/main", "androidApp/src/main"]
    for root in roots:
        for path in (ROOT / root).rglob("*"):
            if path.suffix not in (".rs", ".kt") or "test" in path.name.lower() or path == KOTLIN:
                continue
            source = path.read_text(encoding="utf-8").split("#[cfg(test)]\nmod tests")[0]
            for match in re.finditer(r'(?<![\w.])(?:t|tr!?)\(\s*("(?:\\.|[^"\\])*")', source):
                key = json.loads(match[1])
                if key not in keys:
                    raise ValueError(f"Missing catalog key in {path.relative_to(ROOT)}: {key}")
    def quoted(value):
        return json.dumps(value, ensure_ascii=False).replace("$", "\\$")
    rows = []
    for source, translated in pairs:
        if not translated.strip():
            raise ValueError(f"Missing translation: {source}")
        placeholders = lambda value: sorted(set(re.findall(r"\{([0-9]+)\}", value)))
        if placeholders(source) != placeholders(translated):
            raise ValueError(f"Placeholder mismatch: {source}")
        rows.append(f"        {quoted(source)} to {quoted(translated)},")
    return "\n".join([
        "// Generated by scripts/generate_locales.py from locales/en.json. Do not edit.",
        "package kim.jujin.rovessh.core", "", "internal object EnglishCatalog {",
        "    val messages: Map<String, String> = mapOf(", *rows, "    )", "}", "",
    ])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not KOTLIN.exists() or KOTLIN.read_text(encoding="utf-8") != expected:
            raise SystemExit("Kotlin UI catalog is stale. Run python3 scripts/generate_locales.py")
    else:
        KOTLIN.write_text(expected, encoding="utf-8")
    print("UI catalog and numbered placeholders verified")

if __name__ == "__main__":
    main()
