#!/usr/bin/env python3
"""Validate the shared UI string resources and generate the Rust/Kotlin catalogs (no build dependency)."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ROOT / "locales"
# Order shown in language pickers. Every language has the same keys as BASE.
LANGUAGES = ["ko", "en", "ja"]
BASE = "en"
RUST = ROOT / "crates/dgl-core/src/i18n_catalog.rs"
KOTLIN = ROOT / "app/src/commonMain/kotlin/kim/jujin/dglc/core/UiCatalog.kt"
SOURCE_ROOTS = ["desktop/src", "crates/dgl-core/src", "crates/dgl-core/tests", "crates/dgl-uniffi/src",
                "app/src", "mobileUi/src", "androidApp/src"]
KEY = re.compile(r"[a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+")
CALL = re.compile(r'(?<![\w.])(?:t|tr!?)\(\s*("(?:\\.|[^"\\])*")')
LITERAL = re.compile(r'"((?:[a-z][a-z0-9_]*)(?:\.[a-z0-9_]+)+)"')
HEADER = "Generated by scripts/generate_locales.py from locales/*.json. Do not edit."


def placeholders(value):
    return sorted(set(re.findall(r"\{([0-9]+)\}", value)))


def load():
    catalogs = {}
    for code in LANGUAGES:
        pairs = json.loads((LOCALES / f"{code}.json").read_text(encoding="utf-8"), object_pairs_hook=list)
        keys = [key for key, _ in pairs]
        if len(set(keys)) != len(keys):
            raise ValueError(f"Duplicate key in locales/{code}.json")
        if keys != sorted(keys):
            raise ValueError(f"Keys in locales/{code}.json must be sorted")
        catalogs[code] = dict(pairs)
    stray = sorted(p.stem for p in LOCALES.glob("*.json") if p.stem not in LANGUAGES)
    if stray:
        raise ValueError(f"Register locales in LANGUAGES or remove them: {', '.join(stray)}")
    base = catalogs[BASE]
    for key in base:
        if not KEY.fullmatch(key):
            raise ValueError(f"Invalid key (expected area.meaning): {key}")
    for code, catalog in catalogs.items():
        missing = sorted(base.keys() - catalog.keys())
        extra = sorted(catalog.keys() - base.keys())
        if missing or extra:
            raise ValueError(f"locales/{code}.json differs from {BASE}: missing {missing[:5]} extra {extra[:5]}")
        for key, text in catalog.items():
            if not text.strip():
                raise ValueError(f"Missing {code} text: {key}")
            if placeholders(text) != placeholders(base[key]):
                raise ValueError(f"Placeholder mismatch in {code}: {key}")
    return catalogs


def check_sources(keys):
    used = set()
    for root in SOURCE_ROOTS:
        for path in (ROOT / root).rglob("*"):
            if path.suffix not in (".rs", ".kt") or path in (RUST, KOTLIN):
                continue
            source = path.read_text(encoding="utf-8")
            used.update(LITERAL.findall(source))
            for match in CALL.finditer(source):
                key = json.loads(match[1])
                if key not in keys:
                    raise ValueError(f"Unknown UI text key in {path.relative_to(ROOT)}: {key}")
    unused = sorted(keys - used)
    if unused:
        raise ValueError(f"Unused UI text keys: {', '.join(unused[:10])}")


def rust():
    rows = [f'    ("{code}", include_str!("../../../locales/{code}.json")),' for code in LANGUAGES]
    return "\n".join([
        f"// {HEADER}", "", f'pub(crate) const BASE: &str = "{BASE}";',
        "pub(crate) const LOCALES: &[(&str, &str)] = &[", *rows, "];", "",
    ])


def kotlin(catalogs):
    def quoted(value):
        return json.dumps(value, ensure_ascii=False).replace("$", "\\$")
    lines = [f"// {HEADER}", "package kim.jujin.dglc.core", "",
             "internal object UiCatalog {",
             f"    const val BASE = {quoted(BASE)}",
             f"    val languages: List<String> = listOf({', '.join(quoted(code) for code in LANGUAGES)})",
             "    fun messages(code: String): Map<String, String>? = when (code) {",
             *[f"        {quoted(code)} -> UiCatalog{code.capitalize()}.messages" for code in LANGUAGES],
             "        else -> null", "    }", "}", ""]
    # One object per language keeps each static initializer below the JVM method size limit.
    for code in LANGUAGES:
        lines += [f"private object UiCatalog{code.capitalize()} {{", "    val messages: Map<String, String> = mapOf(",
                  *[f"        {quoted(key)} to {quoted(text)}," for key, text in catalogs[code].items()],
                  "    )", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalogs = load()
    check_sources(set(catalogs[BASE]))
    outputs = {RUST: rust(), KOTLIN: kotlin(catalogs)}
    for path, expected in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale. Run python3 scripts/generate_locales.py")
        else:
            path.write_text(expected, encoding="utf-8")
    print(f"UI text keys verified for {', '.join(LANGUAGES)}")


if __name__ == "__main__":
    main()
