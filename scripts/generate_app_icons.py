#!/usr/bin/env python3
"""Regenerate checked-in app icons. Only this opt-in tool requires Pillow."""
import argparse
from io import BytesIO
import json
from pathlib import Path
import struct

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ART = Path("assets/app-icon")
RES = Path("androidApp/src/main/res")
BACKGROUND = "#11151B"
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)
# 64px is the 32pt @2x entry; use the standard macOS point/Retina slots.
ICNS_TYPES = ((b"icp4", 16), (b"icp5", 32),
              (b"ic07", 128), (b"ic08", 256), (b"ic09", 512), (b"ic10", 1024),
              (b"ic11", 32), (b"ic12", 64), (b"ic13", 256), (b"ic14", 512))


def png(image):
    data = BytesIO()
    image.save(data, format="PNG", optimize=True)
    return data.getvalue()


def resize(image, size):
    return image.resize((size, size), Image.Resampling.LANCZOS)


def monochrome(geometry, size):
    """Flatten our M/L/C/Z contours for the same vector's antialiased preview."""
    scale = size * 4 / geometry["viewport"]
    mask = Image.new("L", (size * 4, size * 4))
    draw = ImageDraw.Draw(mask)
    for index, contour in enumerate(geometry["contours"]):
        points = []
        for command, *values in contour:
            if command in ("M", "L"):
                current = tuple(values)
                points.append(current)
            elif command == "C":
                start = current
                for step in range(1, 33):
                    t = step / 32
                    points.append(tuple((1-t)**3 * start[axis]
                                        + 3*(1-t)**2*t * values[axis]
                                        + 3*(1-t)*t*t * values[axis+2]
                                        + t**3 * values[axis+4] for axis in (0, 1)))
                current = tuple(values[4:])
            elif command != "Z":
                raise ValueError(f"Unsupported monochrome command: {command}")
        draw.polygon([(round(x*scale), round(y*scale)) for x, y in points],
                     fill=255 if index == 0 else 0)
    return mask.resize((size, size), Image.Resampling.LANCZOS)


def vector(geometry):
    path = " ".join(" ".join(map(str, segment)) for contour in geometry["contours"] for segment in contour)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/generate_app_icons.py; edit assets/app-icon/monochrome.json. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f'    <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="{path}" />\n'
            '</vector>\n').encode()


def icns(image):
    chunks = []
    for kind, size in ICNS_TYPES:
        data = png(resize(image, size))
        chunks.append(kind + struct.pack(">I", len(data) + 8) + data)
    body = b"".join(chunks)
    return b"icns" + struct.pack(">I", len(body) + 8) + body


def generate():
    source = Image.open(ROOT / ART / "source.png")
    if source.mode != "RGBA" or source.width != source.height or source.width < 1024:
        raise ValueError("source.png must be square RGBA, at least 1024px")
    if source.getchannel("A").getextrema() != (0, 255):
        raise ValueError("source.png must retain its transparent background")
    master = resize(source, 1024)
    icon = Image.new("RGBA", master.size, BACKGROUND)
    icon.alpha_composite(master)
    macos = Image.new("RGBA", (1024, 1024))
    tile = Image.new("RGBA", (896, 896), BACKGROUND)
    tile.alpha_composite(resize(master, 896))
    tile_mask = Image.new("L", (896, 896))
    ImageDraw.Draw(tile_mask).rounded_rectangle((0, 0, 895, 895), radius=196, fill=255)
    macos.paste(tile, (64, 64), tile_mask)
    geometry = json.loads((ROOT / ART / "monochrome.json").read_text())
    outputs = {ART / "master.png": png(master), ART / "icon.png": png(icon), ART / "macos.png": png(macos),
               RES / "drawable/ic_launcher_monochrome.xml": vector(geometry),
               Path("desktop/resources/dgl.icns"): icns(macos)}
    ico = BytesIO()
    icon.save(ico, format="ICO", sizes=[(size, size) for size in ICO_SIZES])
    outputs[Path("desktop/resources/windows/dgl.ico")] = ico.getvalue()

    # Fit visible artwork inside a 64dp circle within the 108dp layer. Ignore
    # near-transparent generator residue only when measuring; preserve alpha.
    alpha = master.getchannel("A")
    radius = max(((x-511.5)**2 + (y-511.5)**2)**0.5
                 for y in range(1024) for x in range(1024) if alpha.getpixel((x, y)) >= 16)
    factor = (32 / 108) / (radius / 1024)

    def foreground(size):
        layer = Image.new("RGBA", (size, size))
        scaled = resize(master, round(size * factor))
        offset = (size - scaled.width) // 2
        layer.alpha_composite(scaled, (offset, offset))
        return layer

    for density, size in (("mdpi", 108), ("hdpi", 162), ("xhdpi", 216),
                          ("xxhdpi", 324), ("xxxhdpi", 432)):
        outputs[RES / f"drawable-{density}/ic_launcher_foreground.png"] = png(foreground(size))

    sheet = Image.new("RGB", (600, 250), "#20262E")
    draw = ImageDraw.Draw(sheet)
    x = 16
    for size in (128, 48, 32, 16):
        thumb = resize(icon, size)
        sheet.paste(thumb.convert("RGB"), (x, 34))
        draw.text((x, 12), f"{size}px", fill="white")
        if size <= 48:
            sheet.paste(thumb.resize((96, 96), Image.Resampling.NEAREST).convert("RGB"), (x, 144))
        x += 150
    outputs[ART / "preview-sizes.png"] = png(sheet)

    sheet = Image.new("RGB", (800, 240), "#20262E")
    draw = ImageDraw.Draw(sheet)
    layer = foreground(432)
    for index, (name, rounded, themed) in enumerate((("Circle", False, False), ("Rounded square", True, False),
                                                    ("Mono circle", False, True), ("Mono rounded", True, True))):
        if themed:
            layer = Image.new("RGBA", (432, 432), "#C8F288")
            layer.putalpha(monochrome(geometry, 432))
        canvas = Image.new("RGBA", (432, 432), "#26351D" if themed else BACKGROUND)
        canvas.alpha_composite(layer)
        # Android's static viewport is the central 72dp of each 108dp layer.
        canvas = canvas.crop((72, 72, 360, 360)).resize((176, 176), Image.Resampling.LANCZOS)
        mask = Image.new("L", canvas.size)
        painter = ImageDraw.Draw(mask)
        if rounded:
            painter.rounded_rectangle((0, 0, 175, 175), radius=40, fill=255)
        else:
            painter.ellipse((0, 0, 175, 175), fill=255)
        sheet.paste(canvas.convert("RGB"), (12 + 200*index, 40), mask)
        draw.text((12 + 200*index, 16), name, fill="white")
    outputs[ART / "preview-android.png"] = png(sheet)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated assets without writing")
    args = parser.parse_args()
    mismatches = []
    for relative, data in generate().items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        raise SystemExit("Stale app icons:\n" + "\n".join(mismatches))
    print("App icons match sources." if args.check else "Generated app icons and previews.")


if __name__ == "__main__":
    main()
