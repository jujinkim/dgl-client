#!/usr/bin/env python3
"""Generate Compose vectors and embedded GPUI assets from the shared SVGs."""
import argparse
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/ui-icons"
KOTLIN = ROOT / "app/src/jvmSharedMain/kotlin/kim/jujin/dglc/ui/UiIcons.kt"
RUST = ROOT / "desktop/src/ui_icons.rs"
SVG = "{http://www.w3.org/2000/svg}"


def read_icons(source=SOURCE):
    icons = []
    expected = dict(width="24", height="24", viewBox="0 0 24 24", fill="none",
                    stroke="#000000", **{"stroke-width": "1.8", "stroke-linecap": "round", "stroke-linejoin": "round"})
    for path in sorted(source.glob("*.svg")):
        root = ET.fromstring(path.read_text())
        if not re.fullmatch(r"[a-z]+(?:-[a-z]+)*", path.stem) or root.tag != SVG + "svg" or root.attrib != expected:
            raise ValueError(f"{path}: expected a 24×24 monochrome outline SVG")
        paths = []
        for node in root:
            if node.tag != SVG + "path" or set(node.attrib) != {"d"} or not re.fullmatch(r"[MmLlHhVvCcSsQqTtAaZz0-9., +\-]+", node.attrib["d"]):
                raise ValueError(f"{path}: only plain SVG paths are supported")
            paths.append(node.attrib["d"])
        if not paths:
            raise ValueError(f"{path}: empty icon")
        icons.append((path.stem, ''.join(s.title() for s in path.stem.split('-')), paths))
    if not icons:
        raise ValueError("no UI icons found")
    return icons


def outputs(icons):
    kotlin = '''// Generated by scripts/generate_ui_icons.py. Edit assets/ui-icons/*.svg.
package kim.jujin.dglc.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

internal object UiIcons {
    private fun outline(name: String, data: String) = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {
        addPath(PathParser().parsePathString(data).toNodes(), fill = null, stroke = SolidColor(Color.Black),
            strokeLineWidth = 1.8f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)
    }.build()
'''
    for name, variant, paths in icons:
        kotlin += f'    val {variant[0].lower() + variant[1:]}: ImageVector by lazy {{ outline("{variant}", "{" ".join(paths)}") }}\n'
    kotlin += '}\n'
    rust = '''// Generated by scripts/generate_ui_icons.py. Edit assets/ui-icons/*.svg.
use gpui::{Styled, Svg, px, rgb, svg};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum UiIcon {
'''
    rust += ''.join(f'    {variant},\n' for _, variant, _ in icons) + '}\n\nimpl UiIcon {\n'
    rust += '    pub const ALL: &[Self] = &[\n' + ''.join(f'        Self::{v},\n' for _, v, _ in icons) + '    ];\n'
    rust += "    pub fn path(self) -> &'static str {\n        match self {\n"
    rust += ''.join(f'            Self::{v} => "ui-icons/{n}.svg",\n' for n, v, _ in icons) + '        }\n    }\n'
    rust += "    pub fn bytes(self) -> &'static [u8] {\n        match self {\n"
    rust += ''.join(f'            Self::{v} => include_bytes!("../../assets/ui-icons/{n}.svg"),\n' for n, v, _ in icons) + '        }\n    }\n'
    rust += '''    pub fn render(self, color: u32) -> Svg {
        svg()
            .path(self.path())
            .size(px(16.))
            .flex_shrink_0()
            .text_color(rgb(color))
    }
}
'''
    return {KOTLIN: kotlin, RUST: rust}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs(read_icons()).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        sys.exit('UI icon outputs are stale; run scripts/generate_ui_icons.py: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
